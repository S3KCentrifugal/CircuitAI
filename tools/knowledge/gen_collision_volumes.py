"""Generate src/circuit/unit/CollisionVolumes.h from the BAR game's unit files.

The engine measures area damage to a unit's collision volume surface
(headless calibration 2026-11-02, BAR/nuke-chain-runs/RESULTS.md: exact to
under 1 elmo for cylinders and boxes), and the AI interface exposes no
collision volume, so the nuke chain-kill score (CSuperTask::ChainKill) reads
this table. Only static units (no movement speed) are listed; anything absent
falls back to the def radius x nuclear.blast_volume_factor.

python tools/knowledge/gen_collision_volumes.py --bar <BAR game repo>
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/circuit/unit/CollisionVolumes.h'
TYPES = {'cyly': 'CYL_Y', 'cylx': 'CYL_X', 'cylz': 'CYL_Z', 'box': 'BOX', 'ellipsoid': 'SPHERE', 'ell': 'SPHERE', 'sphere': 'SPHERE'}


def top(text, key):
    """a key of the unit's own table (two tabs deep), not of featuredefs or customparams"""
    m = re.search(r'\n\t\t%s\s*=\s*"?([^",\n]*)"?\s*,' % key, text, re.I)
    return m.group(1).strip() if m else None


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--bar', required=True, help='BAR game repository (read only)')
    a = p.parse_args()
    rows = []
    for f in sorted(Path(a.bar, 'units').rglob('*.lua')):
        if 'scav' in str(f.relative_to(a.bar)).lower():
            continue
        t = f.read_text(encoding='utf-8', errors='replace')
        m = re.match(r'\s*return\s*\{\s*\n\t(\w+)\s*=\s*\{', t)
        if not m:
            continue
        speed = top(t, 'speed') or top(t, 'maxvelocity')
        if speed and float(speed) > 0:
            continue
        vt, vs = top(t, 'collisionvolumetype'), top(t, 'collisionvolumescales')
        if not vt or not vs or vt.lower() not in TYPES:
            continue
        s = [float(x) for x in vs.split()]
        o = [float(x) for x in (top(t, 'collisionvolumeoffsets') or '0 0 0').split()]
        if len(s) != 3 or len(o) != 3:
            continue
        rows.append((m.group(1).lower(), TYPES[vt.lower()], s, o, f.relative_to(a.bar).as_posix()))
    body = '\n'.join('\t{"%s", CV::%s, %g, %g, %g, %g, %g, %g},  // %s' % (n, k, s[0], s[1], s[2], o[0], o[1], o[2], src)
                     for n, k, s, o, src in rows)
    OUT.write_text('''// GENERATED by tools/knowledge/gen_collision_volumes.py from the BAR game's unit files; do not edit.
// Collision volumes of static units: collisionvolumetype / scales (full sizes x y z) / offsets.
// The engine measures area damage to this volume's surface; see CSuperTask::ChainKill.
#ifndef SRC_CIRCUIT_UNIT_COLLISIONVOLUMES_H_
#define SRC_CIRCUIT_UNIT_COLLISIONVOLUMES_H_

namespace circuit {
namespace CV {

enum Type { CYL_Y, CYL_X, CYL_Z, BOX, SPHERE };

struct SVolume {
	const char* name;
	Type type;
	float sx, sy, sz;  // full sizes
	float ox, oy, oz;  // offsets from the unit position
};

static const SVolume volumes[] = {
%s
};

}  // namespace CV
}  // namespace circuit

#endif  // SRC_CIRCUIT_UNIT_COLLISIONVOLUMES_H_
''' % body, encoding='utf-8', newline='\n')
    print('%d static unit volumes -> %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
